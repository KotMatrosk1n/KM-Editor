const ModuleRange* FindExactMain(const ModuleRange* modules, size_t module_count) {
    const ModuleRange* match = nullptr;
    for (size_t index = 0; index < module_count; ++index) {
        if (!MatchesExactProfile(modules[index])) {
            continue;
        }
        if (match != nullptr) {
            return nullptr;
        }
        match = &modules[index];
    }
    return match;
}

bool ValuesEqual(const SettingsValues& left, const SettingsValues& right) {
    return left.experience_share == right.experience_share
        && left.experience_rate_basis_points == right.experience_rate_basis_points
        && left.level_cap_enabled == right.level_cap_enabled
        && left.level_cap == right.level_cap;
}

bool IsNativeRepresentable(const SettingsState& state) {
    const auto& values = state.values;
    return (state.presence & RequiredPresence) == RequiredPresence
        && values.experience_rate_basis_points <= 50000
        && values.experience_rate_basis_points % 1000 == 0
        && ((!values.level_cap_enabled && values.level_cap == 100)
            || (values.level_cap_enabled && values.level_cap >= 1
                && values.level_cap <= 100));
}

