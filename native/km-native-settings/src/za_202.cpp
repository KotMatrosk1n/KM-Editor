extern "C" bool km_try_activate_za_202(
    const km::ModuleRange* modules,
    size_t module_count,
    const km::GuestFilesystemApi* filesystem) {
    if (modules == nullptr || filesystem == nullptr
        || filesystem->mount_sd == nullptr || filesystem->open_file == nullptr
        || filesystem->read_file == nullptr || filesystem->write_file == nullptr
        || filesystem->get_file_size == nullptr || filesystem->flush_file == nullptr
        || filesystem->close_file == nullptr) {
        return false;
    }

    uint64_t program_id = 0;
    if (km::km_svc_get_info(
            &program_id,
            ProgramIdInfoType,
            km::CurrentProcessPseudoHandle,
            0) != km::ResultSuccess
        || program_id != TitleId) {
        return false;
    }
    const auto state = __atomic_load_n(&g_activation_state, __ATOMIC_ACQUIRE);
    if (state == ActivationActive || state == ActivationRetrying) {
        return true;
    }
    if (state == ActivationRejected) {
        return false;
    }
    const auto* exact = FindExactMain(modules, module_count);
    if (exact == nullptr) {
        return false;
    }
    uint32_t idle = ActivationIdle;
    if (!__atomic_compare_exchange_n(
            &g_activation_state,
            &idle,
            ActivationRetrying,
            false,
            __ATOMIC_ACQ_REL,
            __ATOMIC_ACQUIRE)) {
        return idle == ActivationActive || idle == ActivationRetrying;
    }

    g_main = *exact;
    g_filesystem = *filesystem;
    km_za_202_main_base = exact->base;
    if (!PrepareValueMessageKeys()) {
        __atomic_store_n(
            &g_activation_state, ActivationRejected, __ATOMIC_RELEASE);
        return false;
    }

    SettingsState loaded{};
    const auto journal_ready = km::LoadSettingsJournal(
            g_filesystem,
            JournalPath,
            SettingsFamily::LegendsZA,
            TitleId,
            RequiredPresence,
            &loaded);
    if (!journal_ready) {
        loaded = SettingsState{
            SettingsFamily::LegendsZA,
            TitleId,
            0,
            RequiredPresence,
            km::VanillaSettings,
            0,
            false,
        };
    }

    // This call runs directly from the subsdk module entry while the loader is
    // still starting the process. Install the complete immutable hook set now,
    // with a fail-safe vanilla snapshot when SD is not ready. No later journal
    // or menu operation is permitted to modify executable memory.
    if (!InstallRuntime(loaded, journal_ready)) {
        __atomic_store_n(
            &g_activation_state, ActivationRejected, __ATOMIC_RELEASE);
        return false;
    }
    if (journal_ready) {
        return true;
    }
    StartJournalRetryWorker();
    return true;
}

extern "C" uint32_t km_za_202_row_count(void* model) {
    if (model == nullptr) {
        return 0;
    }
    const auto category = ReadCategory(model);
    if (category >= 3) {
        return 0;
    }
    const auto active = IsActive();
    if (active && category == 2 && !IsJournalReady()) {
        // If the loader-time worker launch failed transiently, opening this
        // stock page safely retries only authenticated data adoption.
        StartJournalRetryWorker();
    }
    return active && category == 2 ? 6 : 3;
}

extern "C" KmZa202RowDescriptor km_za_202_get_row(
    void* page, uint32_t row) {
    if (page == nullptr) {
        return {};
    }
    auto* model = ReadModel(page);
    if (model == nullptr) {
        return {};
    }
    const auto category = ReadCategory(model);
    if (IsActive() && category == 2 && row >= 3 && row < 6) {
        return ReadCustomDescriptor(row);
    }
    return ReadStockDescriptor(model, row);
}

extern "C" bool km_za_202_step_right(void* page) {
    if (page == nullptr) {
        return false;
    }
    auto* model = ReadModel(page);
    if (model == nullptr) {
        return false;
    }
    const auto row = *reinterpret_cast<const uint32_t*>(
        reinterpret_cast<const uint8_t*>(model) + 0xBC);
    if (IsActive() && ReadCategory(model) == 2 && (row == 4 || row == 5)) {
        return StepCustomRow(page, row, true);
    }
    const auto descriptor = km_za_202_get_row(page, row);
    if (descriptor.kind != 2) {
        return false;
    }
    const auto maximum = descriptor.flags == 0 ? 5U : 10U;
    if (descriptor.value >= maximum) {
        return false;
    }
    const auto value = descriptor.value + 1U;
    km_za_202_apply_row(page, row, value);
    RefreshRow(page, row, descriptor, value, true);
    return true;
}

extern "C" bool km_za_202_step_left(void* page) {
    if (page == nullptr) {
        return false;
    }
    auto* model = ReadModel(page);
    if (model == nullptr) {
        return false;
    }
    const auto row = *reinterpret_cast<const uint32_t*>(
        reinterpret_cast<const uint8_t*>(model) + 0xBC);
    if (IsActive() && ReadCategory(model) == 2 && (row == 4 || row == 5)) {
        return StepCustomRow(page, row, false);
    }
    const auto descriptor = km_za_202_get_row(page, row);
    if (descriptor.kind != 2) {
        return false;
    }
    const auto minimum = descriptor.flags == 0 ? 1U : 0U;
    if (descriptor.value <= minimum) {
        return false;
    }
    const auto value = descriptor.value - 1U;
    km_za_202_apply_row(page, row, value);
    RefreshRow(page, row, descriptor, value, false);
    return true;
}

extern "C" void km_za_202_apply_row(
    void* page, uint32_t row, uint32_t value) {
    if (page == nullptr) {
        return;
    }
    auto* model = ReadModel(page);
    if (model == nullptr) {
        return;
    }
    const auto category = ReadCategory(model);
    if (IsActive() && category == 2 && row >= 3 && row < 6) {
        if (!IsJournalReady()) {
            StartJournalRetryWorker();
            return;
        }
        AcquireMenuLock();
        if (!IsJournalReady()) {
            ReleaseMenuLock();
            return;
        }
        auto next = g_draft;
        auto valid = true;
        switch (row) {
        case 3:
            if (value > 1) {
                valid = false;
            } else {
                next.experience_share = value == 0;
            }
            break;
        case 4:
            if (value > 50) {
                valid = false;
            } else {
                next.experience_rate_basis_points = value * 1000U;
            }
            break;
        case 5:
            if (value > 100) {
                valid = false;
            } else if (value == 0) {
                next.level_cap_enabled = false;
                next.level_cap = 100;
            } else {
                next.level_cap_enabled = true;
                next.level_cap = static_cast<uint8_t>(value);
            }
            break;
        default:
            valid = false;
            break;
        }
        if (valid) {
            StoreDraft(next);
        }
        ReleaseMenuLock();
        return;
    }

    using Apply = void (*)(void*, uint32_t, uint32_t);
    switch (category) {
    case 0:
        MainFunction<Apply>(ApplyCategory0Offset)(model, row, value);
        break;
    case 1:
        MainFunction<Apply>(ApplyCategory1Offset)(model, row, value);
        break;
    case 2:
        MainFunction<Apply>(ApplyCategory2Offset)(model, row, value);
        break;
    default:
        break;
    }
}

extern "C" void km_za_202_render_row(
    void* text_view,
    void* row_handle,
    uint32_t category,
    uint32_t row,
    uint32_t value) {
    if (text_view == nullptr || row_handle == nullptr) {
        return;
    }
    using StockRender = void (*)(void*, void*, uint32_t, uint32_t);
    using SetTitle = void (*)(void*, void*, const MessageKey*);
    using SetToggle = void (*)(void*, void*, const MessageKey*, const MessageKey*);
    using SetSlider = void (*)(void*, void*, uint32_t);
    if (IsActive() && category == 2 && row >= 3 && row < 6) {
        const MessageKey* title = &ExperienceShareNameKey;
        if (row == 4 && value <= 50) {
            title = &g_experience_rate_value_keys[value];
        } else if (row == 4) {
            title = &ExperienceRateNameKey;
        } else if (row == 5 && value == 0) {
            title = &LevelCapOffKey;
        } else if (row == 5 && value <= 100) {
            title = &g_level_cap_value_keys[value - 1];
        } else if (row == 5) {
            title = &LevelCapNameKey;
        }
        MainFunction<SetTitle>(SetRowTitleOffset)(text_view, row_handle, title);
        if (row == 3) {
            MainFunction<SetToggle>(SetToggleLabelsOffset)(
                text_view, row_handle, &EnabledKey, &DisabledKey);
        } else {
            MainFunction<SetSlider>(SetSliderValueOffset)(
                text_view, row_handle, CustomSliderVisualValue(row, value));
        }
        return;
    }
    switch (category) {
    case 0:
        MainFunction<StockRender>(RenderCategory0Offset)(
            text_view, row_handle, row, value);
        break;
    case 1:
        MainFunction<StockRender>(RenderCategory1Offset)(
            text_view, row_handle, row, value);
        break;
    case 2:
        MainFunction<StockRender>(RenderCategory2Offset)(
            text_view, row_handle, row, value);
        break;
    default:
        break;
    }
}

