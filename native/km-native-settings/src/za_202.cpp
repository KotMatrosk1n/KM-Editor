struct MessageKey {
    uint64_t hash;
    const char* name;
    uint64_t length;
};
static_assert(sizeof(MessageKey) == 0x18);

constexpr uint64_t FnvOffsetBasis = 0xCBF29CE484222645ULL;
constexpr uint64_t FnvPrime = 0x100000001B3ULL;

constexpr uint64_t HashMessageKey(const char* value, size_t length) {
    auto hash = FnvOffsetBasis;
    for (size_t index = 0; index < length; ++index) {
        hash ^= static_cast<uint8_t>(value[index]);
        hash *= FnvPrime;
    }
    return hash;
}

template <size_t Length>
constexpr MessageKey MakeMessageKey(const char (&value)[Length]) {
    static_assert(Length > 1);
    return MessageKey{HashMessageKey(value, Length - 1), value, Length - 1};
}

